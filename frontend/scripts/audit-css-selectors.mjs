import { readFileSync, readdirSync } from "node:fs";
import { join, relative } from "node:path";
import postcss from "postcss";

const root = new URL("..", import.meta.url).pathname;
const cssFiles = ["src/styles.css", "src/reference-console.css", "src/operations-console.css"];

function walk(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

const sourceFiles = walk(join(root, "src")).filter((path) => /\.(?:ts|tsx|html)$/.test(path));
const sources = sourceFiles.map((path) => ({
  path: relative(root, path),
  text: readFileSync(path, "utf8"),
}));

function consumers(className) {
  const direct = sources.filter(({ text }) => text.includes(className)).map(({ path }) => path);
  if (direct.length) return { kind: "direct", files: direct };
  const separator = Math.max(className.lastIndexOf("--"), className.lastIndexOf("is-"));
  const prefix = separator > 0 ? className.slice(0, separator + 2) : "";
  const inferred = prefix
    ? sources.filter(({ text }) => text.includes(prefix)).map(({ path }) => path)
    : [];
  return inferred.length
    ? { kind: "runtime modifier", files: inferred }
    : { kind: "no source consumer", files: [] };
}

console.log("# CSS selector usage inventory\n");
console.log(
  "Generated by `node scripts/audit-css-selectors.mjs`. Runtime modifier rows require review before deletion.\n",
);

for (const cssFile of cssFiles) {
  const css = readFileSync(join(root, cssFile), "utf8");
  const rootNode = postcss.parse(css, { from: cssFile });
  const classes = new Map();
  rootNode.walkRules((rule) => {
    for (const match of rule.selector.matchAll(/\.([_a-zA-Z]+[\w-]*)/g)) {
      const className = match[1];
      const entry = classes.get(className) ?? { rules: 0, lines: [] };
      entry.rules += 1;
      if (rule.source?.start?.line) entry.lines.push(rule.source.start.line);
      classes.set(className, entry);
    }
  });
  const rows = [...classes.entries()].map(([className, entry]) => ({
    className,
    ...entry,
    ...consumers(className),
  }));
  const counts = Object.groupBy(rows, (row) => row.kind);
  console.log(`## ${cssFile}\n`);
  console.log(`- Unique classes: ${rows.length}`);
  console.log(`- Direct consumers: ${counts.direct?.length ?? 0}`);
  console.log(`- Runtime modifiers: ${counts["runtime modifier"]?.length ?? 0}`);
  console.log(`- No source consumer: ${counts["no source consumer"]?.length ?? 0}\n`);
  console.log("| Selector | Classification | Rules | First line | Consumers |");
  console.log("|---|---|---:|---:|---|");
  for (const row of rows.sort((left, right) => left.className.localeCompare(right.className))) {
    console.log(
      `| \`.${row.className}\` | ${row.kind} | ${row.rules} | ${Math.min(...row.lines)} | ${row.files.join("<br>") || "—"} |`,
    );
  }
  console.log("");
}
